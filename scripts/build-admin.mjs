import { readFileSync, writeFileSync } from 'node:fs';
const source = readFileSync(new URL('../admin-client.js', import.meta.url), 'utf8').replace(/^export function dashboardApp/, 'function dashboardApp');
const output = '// Generated by scripts/build-admin.mjs. Edit admin-client.js instead.\nexport const DASHBOARD_SCRIPT = ' + JSON.stringify(source) + ';\n';
const target = new URL('../admin-client.generated.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Dashboard asset is stale. Run npm run build:admin.');
} else writeFileSync(target, output);
