import { readdir, readFile, writeFile, lstat } from 'node:fs/promises';
import { dirname, join, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { validateKnowledgeDocument, isPublicKnowledge, KNOWLEDGE_PRODUCTS, containsSensitiveKnowledge } from '../knowledge-schema.js';
import { indexKnowledgeDocument } from '../knowledge-index.js';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const folders = { playsmart: 'PLAYSMART', readsmart: 'READSMART', skoolio_admin: 'SKOOLIO_ADMIN' };
export async function compileKnowledge(directory) {
  const documents = [], errors = [], ids = new Set(), bodies = new Map();
  const entries = await readdir(directory, { withFileTypes: true });
  for (const entry of entries) if (entry.isDirectory() && !folders[entry.name]) errors.push(`Unknown product directory: ${entry.name}`);
  async function discover(path, product) {
    for (const entry of (await readdir(path, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
      const file = join(path, entry.name), name = relative(directory, file);
      if ((await lstat(file)).isSymbolicLink()) { errors.push(`${name}: symbolic links are not accepted`); continue; }
      if (entry.isDirectory()) { await discover(file, product); continue; }
      if (entry.name.endsWith('.md')) continue; // Human README/gap notes are never indexed.
      if (!entry.name.endsWith('.json')) { errors.push(`${name}: expected a JSON knowledge document`); continue; }
      let doc;
      try { const raw = await readFile(file, 'utf8'); if (raw.length > 30000) throw new Error(); doc = JSON.parse(raw); }
      catch { errors.push(`${name}: malformed or oversized JSON`); continue; }
      const problems = validateKnowledgeDocument(doc);
      if (doc?.product !== product) problems.push('Product does not match folder');
      if (doc?.id && ids.has(doc.id)) problems.push('Duplicate document id');
      ids.add(doc?.id);
      const bodyKey = `${product}:${String(doc?.content).replace(/\s+/g, ' ').trim().toLowerCase()}`;
      if (bodies.has(bodyKey)) problems.push(`Duplicate content (also in ${bodies.get(bodyKey)})`);
      bodies.set(bodyKey, name);
      errors.push(...problems.map(problem => `${name}: ${problem}`));
      if (!problems.length) documents.push(doc);
    }
  }
  for (const [folder, product] of Object.entries(folders)) {
    try { const stat = await lstat(join(directory, folder)); if (!stat.isDirectory() || stat.isSymbolicLink()) throw new Error(); await discover(join(directory, folder), product); }
    catch { errors.push(`${folder}: product directory missing or unreadable`); }
  }
  let collections;
  try {
    collections = JSON.parse(await readFile(join(directory, 'collections.json'), 'utf8'));
    if (!Array.isArray(collections) || collections.length !== 3 || new Set(collections.map(c => c.product)).size !== 3) throw new Error();
    if (containsSensitiveKnowledge(collections)) throw new Error();
    for (const item of collections) if (Object.keys(item).some(key => !['product', 'status', 'missing_areas'].includes(key)) || !KNOWLEDGE_PRODUCTS.includes(item.product) || !['SOURCE_REVIEWED_SEED', 'AWAITING_SOURCE'].includes(item.status) || !Array.isArray(item.missing_areas) || item.missing_areas.some(v => typeof v !== 'string' || v.length > 200)) throw new Error();
  } catch { errors.push('collections.json: invalid collection coverage manifest'); }
  if (errors.length) throw new Error(errors.join('\n'));
  documents.sort((a, b) => a.id.localeCompare(b.id));
  const publicDocuments = documents.filter(isPublicKnowledge);
  const index = Object.fromEntries(publicDocuments.map(doc => [doc.id, indexKnowledgeDocument(doc)]));
  const inventory = documents.map(({ id, product, module, title, document_type, version, updated_at, source, visibility, support_safe }) => ({ id, product, module, title, document_type, version, updated_at, source, visibility, support_safe }));
  const payload = JSON.stringify({ documents: publicDocuments, index, collections, inventory });
  const version = createHash('sha256').update(payload).digest('hex').slice(0, 16);
  const generated = `// Generated by npm run knowledge:build. Edit support_knowledge documents instead.\nexport const KNOWLEDGE_VERSION = ${JSON.stringify(version)};\nexport const KNOWLEDGE_DOCUMENTS = ${JSON.stringify(publicDocuments, null, 2)};\nexport const KNOWLEDGE_INDEX = ${JSON.stringify(index)};\nexport const KNOWLEDGE_COLLECTIONS = ${JSON.stringify(collections, null, 2)};\nexport const KNOWLEDGE_INVENTORY = ${JSON.stringify(inventory, null, 2)};\n`;
  return { generated, version, count: documents.length, publicCount: publicDocuments.length };
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const result = await compileKnowledge(join(root, 'support_knowledge'));
    const path = join(root, 'knowledge.generated.js');
    if (process.argv.includes('--check')) {
      if (await readFile(path, 'utf8').catch(() => '') !== result.generated) throw new Error('Knowledge index is missing or stale. Run npm run knowledge:build.');
    } else if (!process.argv.includes('--validate')) await writeFile(path, result.generated);
    console.log(`Knowledge validated: ${result.count} documents, ${result.publicCount} public support documents, version ${result.version}.`);
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
