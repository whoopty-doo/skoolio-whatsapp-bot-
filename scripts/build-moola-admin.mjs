import { readFileSync, writeFileSync } from 'node:fs';
const source = readFileSync(new URL('../moola-admin-client.js', import.meta.url), 'utf8')
  .replace('export function moolaClient', 'function moolaClient');
const output = '// Generated by scripts/build-moola-admin.mjs. Edit moola-admin-client.js instead.\nexport const MOOLA_SCRIPT = '
  + JSON.stringify(source) + ';\n';
const target = new URL('../moola-admin-client.generated.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw Error('Moola dashboard asset is stale. Run node scripts/build-moola-admin.mjs.');
} else writeFileSync(target, output);
