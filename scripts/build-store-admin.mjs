import { readFileSync, writeFileSync } from 'node:fs';
const source = readFileSync(new URL('../store-admin-client.js', import.meta.url), 'utf8').replace(/^export function storeApp/, 'function storeApp');
const output = '// Generated by scripts/build-store-admin.mjs. Edit store-admin-client.js instead.\nexport const STORE_SCRIPT = ' + JSON.stringify(source) + ';\n';
const target = new URL('../store-admin-client.generated.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw Error('Store dashboard asset is stale. Run npm run build:admin.');
} else writeFileSync(target, output);
